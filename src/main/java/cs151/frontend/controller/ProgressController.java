package cs151.frontend.controller;

import cs151.application.Main;
import cs151.backend.exception.PersistenceException;
import cs151.backend.exception.ValidationException;
import cs151.backend.model.Milestone;
import cs151.backend.model.Task;
import cs151.backend.service.GoalPlanner;
import cs151.frontend.Motion;
import javafx.collections.FXCollections;
import javafx.fxml.FXML;
import javafx.scene.control.ComboBox;
import javafx.scene.control.Label;
import javafx.scene.control.TextArea;
import javafx.scene.control.TextField;
import javafx.util.StringConverter;

import java.io.IOException;
import java.time.LocalDate;

/**
 * Controller of the Progress page (progress-view.fxml). Opened by double-clicking a task on the Task list page.
 * Collects the progress note for a task, hands it to {@link GoalPlanner} (which validates it and stores it
 * permanently with today's date as the entry date) and shows the result as a toast.
 */
public class ProgressController {

    private final GoalPlanner goalPlanner = new GoalPlanner();

    /** The milestone of the opened task; used to go back to that milestone's Task list. */
    private Milestone milestone;

    @FXML
    private Label summaryName;

    @FXML
    private Label summaryDeadline;

    @FXML
    private Label summaryHint;

    @FXML
    private ComboBox<Task> taskComboBox;

    @FXML
    private TextField entryDateField;

    @FXML
    private TextArea noteArea;

    @FXML
    private void initialize() {
        // Show only the task description in the drop-down instead of Task.toString().
        taskComboBox.setConverter(new StringConverter<>() {
            @Override
            public String toString(Task task) {
                return task == null ? "" : task.getDescription();
            }

            @Override
            public Task fromString(String text) {
                return null;
            }
        });

        // The entry date is generated by the backend (always today); it is only displayed here.
        entryDateField.setText(LocalDate.now().toString());
    }

    /**
     * Called by Main right after the page is loaded: remembers the task's milestone, fills the summary card and
     * the drop-down with the tasks of that milestone, and pre-selects the task that was double-clicked.
     */
    public void setTask(Task task) {
        milestone = goalPlanner.getMilestone(task.getMilestoneId());

        summaryName.setText(task.getDescription());
        summaryDeadline.setText(
                "Milestone: " + milestone.getMilestoneName()
                        + "  •  Task due " + task.getDueDate()
        );
        summaryHint.setText("The entry date is set to today automatically.");

        taskComboBox.setItems(
                FXCollections.observableArrayList(
                        goalPlanner.getTasksForMilestone(milestone.getId())
                )
        );

        // Select by id, because the list holds freshly loaded Task objects.
        taskComboBox.getItems().stream()
                .filter(item -> item.getId() == task.getId())
                .findFirst()
                .ifPresent(taskComboBox::setValue);
    }

    /**
     * Reads the form and asks {@link GoalPlanner} to validate and permanently store the progress note under the
     * selected task. A missing task or a failed validation (for example an empty note) is shown as a toast.
     */
    @FXML
    private void saveProgress() {
        Task selected = taskComboBox.getValue();

        if (selected == null) {
            Motion.toast("Task is required.", true);
            return;
        }

        try {
            goalPlanner.addProgressEntry(selected.getId(), noteArea.getText());

            Motion.toast("Progress saved successfully.", false);
            clearForm();
        } catch (ValidationException | PersistenceException exception) {
            Motion.toast(exception.getMessage(), true);
        }
    }

    /** Empties the note after a successful save so another note can be entered. */
    private void clearForm() {
        noteArea.clear();
    }

    @FXML
    private void goBack() throws IOException {
        Main.showTaskListPage(milestone);
    }
}
